def all_deadlines() -> list[Deadline]:
    """Full calendar, sorted chronologically."""
    return sorted(DEADLINES, key=lambda d: d.date)


@validated
def deadlines_for(
    risk_categories: Sequence[RiskCategory],
    *,
    annex_i_product: bool = False,
    include_gdpr: bool = True,
) -> list[Deadline]:
    """Deadlines applicable to a project given its risk category (or categories)."""
    wanted = set(risk_categories)
    selected: list[Deadline] = []
    for deadline in DEADLINES:
        if deadline.regulation is Regulation.GDPR:
            if include_gdpr:
                selected.append(deadline)
            continue
        if deadline.deadline_id == "ai-act-high-risk-annex-i" and not annex_i_product:
            continue
        if wanted.intersection(deadline.applies_to):
            selected.append(deadline)
    return sorted(selected, key=lambda d: d.date)


@validated
def compliance_due_date(risk_category: RiskCategory, *, annex_i_product: bool = False) -> date:
    """Date from which the obligations specific to a risk category become enforceable."""
    match risk_category:
        case RiskCategory.PROHIBITED:
            return AI_ACT_PROHIBITIONS
        case RiskCategory.HIGH_RISK:
            return AI_ACT_HIGH_RISK_ANNEX_I if annex_i_product else AI_ACT_HIGH_RISK_ANNEX_III
        case RiskCategory.GPAI | RiskCategory.GPAI_SYSTEMIC_RISK:
            return AI_ACT_GPAI_GOVERNANCE
        case RiskCategory.NOT_APPLICABLE:
            return GDPR_APPLICATION
        case _:
            return AI_ACT_GENERAL_APPLICATION


