# Chapter III, Section 4: Articles 28 to 39 (notifying authorities, notified bodies).
_CH3_SECTION4 = range(28, 40)


@validated
def ai_act_article_enforcement(article: PositiveInt, chapter: str | None) -> tuple[date, str | None]:
    """Date of application of an AI Act article (post-Omnibus) and explanatory note."""
    if article == 113:
        return AI_ACT_ENTRY_INTO_FORCE, "Entry into force; application timeline."
    if article == 5:
        return (
            AI_ACT_PROHIBITIONS,
            "Prohibitions apply since 02/02/2025; two new prohibitions (nudification, CSAM) "
            f"from 02/12/2026 ({OMNIBUS}).",
        )
    if chapter in {"I", "II"}:
        return AI_ACT_PROHIBITIONS, None
    if article in _CH3_SECTION4:
        return AI_ACT_GPAI_GOVERNANCE, "Chapter III, Section 4 (Art. 113(b))."
    if article == 6:
        return (
            AI_ACT_HIGH_RISK_ANNEX_III,
            f"Annex III: 02/12/2027; Art. 6(1)/Annex I: 02/08/2028 ({OMNIBUS}).",
        )
    if chapter == "III":
        return (
            AI_ACT_HIGH_RISK_ANNEX_III,
            f"Annex III systems: 02/12/2027; Annex I products: 02/08/2028 ({OMNIBUS}).",
        )
    if article == 50:
        return (
            AI_ACT_GENERAL_APPLICATION,
            f"Grace period for Art. 50(2) until 02/12/2026 for existing systems ({OMNIBUS}).",
        )
    if chapter in {"V", "VII"} or article == 78:
        return AI_ACT_GPAI_GOVERNANCE, None
    if chapter == "XII":
        if article == 101:
            return AI_ACT_GENERAL_APPLICATION, "Art. 101 is excluded from Art. 113(b)."
        return AI_ACT_GPAI_GOVERNANCE, None
    if article == 57:
        return AI_ACT_NATIONAL_SANDBOXES, f"National sandboxes postponed ({OMNIBUS})."
    return AI_ACT_GENERAL_APPLICATION, None


@validated
def ai_act_article_risk(article: PositiveInt, chapter: str | None) -> RiskCategory:
    """Risk tier an AI Act article primarily relates to."""
    if article == 5:
        return RiskCategory.PROHIBITED
    if article in {51, 52, 55}:
        return RiskCategory.GPAI_SYSTEMIC_RISK
    if chapter == "V":
        return RiskCategory.GPAI
    if chapter == "III" or article in {71, 72, 73, 86}:
        return RiskCategory.HIGH_RISK
    if article == 50:
        return RiskCategory.LIMITED_RISK
    if article == 95:
        return RiskCategory.MINIMAL_RISK
    return RiskCategory.HORIZONTAL


